#!/usr/bin/env python3
"""Experiment registry for the HMM visual-localization research (see docs/MASTER_RESEARCH_PLAN.md §8).

Every experiment run -- successful, failed or later found invalid -- gets ONE line in
research/registry/runs.jsonl. Findings and paper numbers must cite a run_id from this file.

Usage
  python automation/log_run.py new-id <task_id>            # print a fresh run id, e.g. R20261124-003_T3.2
  python automation/log_run.py add <record.json>            # validate + append a run record
  python automation/log_run.py invalidate <run_id> "<why>"  # mark a run invalid (never delete)
  python automation/log_run.py dashboard                    # regenerate research/DASHBOARD.md
  python automation/log_run.py check                        # validate the whole registry

No third-party dependencies (stdlib only) so it runs locally, on Kaggle and in CI.
"""
import json, os, sys, datetime, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REG = os.path.join(ROOT, "research", "registry", "runs.jsonl")
DASH = os.path.join(ROOT, "research", "DASHBOARD.md")

REQUIRED = ["run_id", "date_utc", "task_id", "hypothesis_ids", "dataset", "method",
            "config", "metrics", "status", "verdict", "evidence_level", "notes"]
STATUS = {"ok", "failed", "invalid", "running"}
VERDICT = {"supports", "refutes", "inconclusive", "n/a"}
# V = verified on real data with the locked protocol; S = supported (real data, dev split / partial);
# P = pilot / synthetic only; R = reported elsewhere, not re-verifiable from this repo.
EVIDENCE = {"V", "S", "P", "R"}


def _load():
    if not os.path.isfile(REG):
        return []
    with open(REG, encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def _save(rows):
    os.makedirs(os.path.dirname(REG), exist_ok=True)
    with open(REG, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n")


def config_hash(cfg):
    return hashlib.sha1(json.dumps(cfg, sort_keys=True).encode()).hexdigest()[:10]


def validate(r):
    errs = [f"missing '{k}'" for k in REQUIRED if k not in r]
    if r.get("status") not in STATUS:
        errs.append(f"status must be one of {sorted(STATUS)}")
    if r.get("verdict") not in VERDICT:
        errs.append(f"verdict must be one of {sorted(VERDICT)}")
    if r.get("evidence_level") not in EVIDENCE:
        errs.append(f"evidence_level must be one of {sorted(EVIDENCE)}")
    if not isinstance(r.get("hypothesis_ids", []), list):
        errs.append("hypothesis_ids must be a list")
    if not isinstance(r.get("metrics", {}), dict):
        errs.append("metrics must be a dict")
    return errs


def new_id(task):
    day = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d")
    n = sum(1 for r in _load() if r["run_id"].startswith("R" + day)) + 1
    return f"R{day}-{n:03d}_{task}"


def add(path):
    r = json.load(open(path, encoding="utf-8"))
    r.setdefault("date_utc", datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"))
    r.setdefault("config_hash", config_hash(r.get("config", {})))
    errs = validate(r)
    if errs:
        sys.exit("INVALID RECORD: " + "; ".join(errs))
    rows = _load()
    if any(x["run_id"] == r["run_id"] for x in rows):
        sys.exit(f"duplicate run_id {r['run_id']}")
    rows.append(r)
    _save(rows)
    print("logged", r["run_id"])


def invalidate(run_id, why):
    rows = _load(); hit = False
    for r in rows:
        if r["run_id"] == run_id:
            r["status"] = "invalid"; r["notes"] = f"[INVALIDATED: {why}] " + r.get("notes", ""); hit = True
    if not hit:
        sys.exit(f"no run {run_id}")
    _save(rows); print("invalidated", run_id)


def _fmt_metrics(m, k=4):
    items = [(a, b) for a, b in m.items() if isinstance(b, (int, float))][:k]
    return ", ".join(f"{a}={b:.3g}" for a, b in items)


def dashboard():
    rows = _load()
    lines = ["# Experiment dashboard (auto-generated by `automation/log_run.py dashboard` -- do not edit)", "",
             f"Total runs: {len(rows)} | ok: {sum(r['status']=='ok' for r in rows)} | "
             f"failed: {sum(r['status']=='failed' for r in rows)} | invalid: {sum(r['status']=='invalid' for r in rows)}", "",
             "## By hypothesis", "", "| Hypothesis | supports | refutes | inconclusive | runs |", "|---|---|---|---|---|"]
    hyp = {}
    for r in rows:
        if r["status"] != "ok":
            continue
        for h in r["hypothesis_ids"]:
            d = hyp.setdefault(h, {"supports": 0, "refutes": 0, "inconclusive": 0, "ids": []})
            if r["verdict"] in d:
                d[r["verdict"]] += 1
            d["ids"].append(r["run_id"])
    for h in sorted(hyp):
        d = hyp[h]
        lines.append(f"| {h} | {d['supports']} | {d['refutes']} | {d['inconclusive']} | {', '.join(d['ids'][-3:])} |")
    lines += ["", "## Last 30 runs", "", "| run_id | task | ev | dataset | method | status | verdict | key metrics |",
              "|---|---|---|---|---|---|---|---|"]
    for r in rows[-30:][::-1]:
        lines.append(f"| {r['run_id']} | {r['task_id']} | {r['evidence_level']} | {r['dataset']} | {r['method']} | "
                     f"{r['status']} | {r['verdict']} | {_fmt_metrics(r['metrics'])} |")
    os.makedirs(os.path.dirname(DASH), exist_ok=True)
    open(DASH, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("wrote", DASH)


def check():
    bad = 0
    for i, r in enumerate(_load()):
        e = validate(r)
        if e:
            bad += 1; print(f"line {i+1} ({r.get('run_id')}): {e}")
    print("registry OK" if not bad else f"{bad} invalid records"); sys.exit(1 if bad else 0)


if __name__ == "__main__":
    a = sys.argv[1:]
    if not a:
        sys.exit(__doc__)
    cmd = a[0]
    if cmd == "new-id" and len(a) == 2: print(new_id(a[1]))
    elif cmd == "add" and len(a) == 2: add(a[1])
    elif cmd == "invalidate" and len(a) == 3: invalidate(a[1], a[2])
    elif cmd == "dashboard": dashboard()
    elif cmd == "check": check()
    else: sys.exit(__doc__)
